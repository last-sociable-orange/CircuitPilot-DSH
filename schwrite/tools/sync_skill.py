"""Keep the standalone `schwrite` skill copy in step with the package it was cut from.

The skill must work when its folder is copied anywhere, so it carries the package instead of
importing the one in this repository. That copy would rot if it were made by hand; this tool
makes it, records exactly what was copied, and can prove the copy is current.

    python tools/sync_skill.py            # refresh the skill from src/schwrite
    python tools/sync_skill.py --check    # exit 1 if the skill copy has drifted
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
SOURCE = REPO / "src" / "schwrite"
#: Where the runnable copy lives. Two layouts exist in practice: a project's
#: `.dsh/skills/`, and a bundle repository's `dsh/skills/`.
CANDIDATES = (
    REPO.parent / ".dsh" / "skills" / "schwrite",
    REPO.parent / "dsh" / "skills" / "schwrite",
)


def default_skill() -> Path:
    for candidate in CANDIDATES:
        if candidate.is_dir():
            return candidate
    return CANDIDATES[0]


SKILL = default_skill()
TARGET = SKILL / "src" / "schwrite"
MANIFEST = SKILL / "MANIFEST.json"


def files(root: Path) -> dict[str, str]:
    """`{relative path: sha256}` for every file worth copying."""
    found: dict[str, str] = {}
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        if "__pycache__" in path.parts or path.suffix not in {".py", ".sexpdata"}:
            if path.name != "LICENSE.sexpdata":
                continue
        found[path.relative_to(root).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    return found


def version() -> str:
    for line in (SOURCE / "__init__.py").read_text(encoding="utf-8").splitlines():
        if line.startswith("__version__"):
            return line.split("=", 1)[1].strip().strip('"').strip("'")
    return "unknown"


def commit() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=REPO, capture_output=True, text=True, check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def check() -> int:
    if not MANIFEST.is_file():
        print(f"no manifest at {MANIFEST}: run sync_skill.py first", file=sys.stderr)
        return 1
    recorded = json.loads(MANIFEST.read_text(encoding="utf-8"))["files"]
    current = files(TARGET)
    if recorded == current:
        print(f"skill copy is current ({len(current)} files, v{version()})")
        return 0
    missing = sorted(set(recorded) - set(current))
    extra = sorted(set(current) - set(recorded))
    changed = sorted(k for k in set(recorded) & set(current) if recorded[k] != current[k])
    print(f"skill copy has drifted: {len(missing)} missing, {len(extra)} extra, "
          f"{len(changed)} changed", file=sys.stderr)
    for label, names in (("missing", missing), ("extra", extra), ("changed", changed)):
        for name in names[:5]:
            print(f"  {label}: {name}", file=sys.stderr)
    print("run `python tools/sync_skill.py` to refresh it", file=sys.stderr)
    return 1


def sync(target_root: Path | None = None) -> int:
    global SKILL, TARGET, MANIFEST
    if target_root is not None:
        SKILL = target_root
        TARGET = SKILL / "src" / "schwrite"
        MANIFEST = SKILL / "MANIFEST.json"
    SKILL.mkdir(parents=True, exist_ok=True)
    if TARGET.exists():
        shutil.rmtree(TARGET)
    shutil.copytree(SOURCE, TARGET, ignore=shutil.ignore_patterns("__pycache__"))
    manifest = {
        "package": "schwrite",
        "version": version(),
        "source_commit": commit(),
        "note": "generated by tools/sync_skill.py — do not edit the copy by hand",
        "files": files(TARGET),
    }
    MANIFEST.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )
    print(f"skill refreshed: {len(manifest['files'])} files, v{version()}, "
          f"source {manifest['source_commit']} -> {TARGET}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="sync_skill", description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify the copy, change nothing")
    parser.add_argument("--target", help="skill folder to write (default: discovered)")
    args = parser.parse_args(argv)
    if args.target:
        root = Path(args.target).resolve()
        globals()["SKILL"] = root
        globals()["TARGET"] = root / "src" / "schwrite"
        globals()["MANIFEST"] = root / "MANIFEST.json"
    return check() if args.check else sync()


if __name__ == "__main__":
    raise SystemExit(main())
